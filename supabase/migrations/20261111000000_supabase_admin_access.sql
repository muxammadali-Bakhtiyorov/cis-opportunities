create table public.activities (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null,
  format text not null default '',
  age text not null default '',
  deadline date,
  location text not null default '',
  description text not null,
  link text not null default '',
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.user_roles (
  user_id uuid primary key references auth.users (id) on delete cascade,
  role text not null check (role = 'admin'),
  created_at timestamptz not null default now()
);

grant select on public.activities to anon, authenticated;
grant insert, update, delete on public.activities to authenticated;
grant usage, select on sequence public.activities_id_seq to authenticated;
grant select on public.user_roles to authenticated;

alter table public.activities enable row level security;
alter table public.user_roles enable row level security;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.user_roles
    where user_id = (select auth.uid())
      and role = 'admin'
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;

create policy "Anyone can read active activities"
  on public.activities for select
  to anon, authenticated
  using (active or (select public.is_admin()));

create policy "Admins can create activities"
  on public.activities for insert
  to authenticated
  with check ((select public.is_admin()));

create policy "Admins can update activities"
  on public.activities for update
  to authenticated
  using ((select public.is_admin()))
  with check ((select public.is_admin()));

create policy "Admins can delete activities"
  on public.activities for delete
  to authenticated
  using ((select public.is_admin()));

create policy "Users can read their own role"
  on public.user_roles for select
  to authenticated
  using (user_id = (select auth.uid()));

