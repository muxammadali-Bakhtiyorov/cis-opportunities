create or replace function public.publish_telegram_event_draft(
  _draft_id bigint,
  _title text,
  _category text,
  _format text,
  _age text,
  _deadline date,
  _location text,
  _description text,
  _link text
)
returns setof public.activities
language plpgsql
security definer
set search_path = ''
as $$
declare
  draft_status text;
  new_activity public.activities;
begin
  if not (select public.is_admin()) then
    raise exception 'Only admins can publish Telegram drafts';
  end if;

  if nullif(trim(coalesce(_title, '')), '') is null
    or nullif(trim(coalesce(_category, '')), '') is null
    or nullif(trim(coalesce(_description, '')), '') is null then
    raise exception 'Title, category, and description are required';
  end if;

  select status
    into draft_status
    from public.telegram_event_drafts
    where id = _draft_id
    for update;

  if not found then
    raise exception 'Telegram draft was not found';
  end if;
  if draft_status <> 'pending' then
    raise exception 'Telegram draft has already been reviewed';
  end if;

  insert into public.activities (
    title, category, format, age, deadline, location, description, link, active
  )
  values (
    trim(_title),
    trim(_category),
    coalesce(_format, ''),
    coalesce(_age, ''),
    _deadline,
    coalesce(_location, ''),
    trim(_description),
    coalesce(_link, ''),
    true
  )
  returning * into new_activity;

  update public.telegram_event_drafts
  set status = 'published',
      published_activity_id = new_activity.id
  where id = _draft_id;

  return next new_activity;
  return;
end;
$$;

revoke all on function public.publish_telegram_event_draft(
  bigint, text, text, text, text, date, text, text, text
) from public;
grant execute on function public.publish_telegram_event_draft(
  bigint, text, text, text, text, date, text, text, text
) to authenticated;
