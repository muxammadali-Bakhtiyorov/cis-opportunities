  using ((select public.is_admin()));

create or replace function public.set_user_admin(
  _target_user_id uuid,
  _grant_admin boolean
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not (select public.is_admin()) then
    raise exception 'Only admins can change admin access';
  end if;

  perform pg_advisory_xact_lock(1397508932);

  if not (select public.is_admin()) then
    raise exception 'Only admins can change admin access';
  end if;

  if _target_user_id is null then
    raise exception 'A user id is required';
  end if;

  if _grant_admin then
    insert into public.user_roles (user_id, role)
    values (_target_user_id, 'admin')
    on conflict (user_id) do nothing;
    return;
  end if;

  if _target_user_id = (select auth.uid()) then
    raise exception 'You cannot remove your own admin access';
  end if;

  perform 1
  from public.user_roles
  where role = 'admin'
  order by user_id
  for update;

  if exists (
    select 1 from public.user_roles
    where user_id = _target_user_id and role = 'admin'
  ) and (select count(*) from public.user_roles where role = 'admin') <= 1 then
    raise exception 'The last admin cannot be removed';
  end if;

  delete from public.user_roles
  where user_id = _target_user_id and role = 'admin';
end;
$$;

revoke all on function public.set_user_admin(uuid, boolean) from public;
grant execute on function public.set_user_admin(uuid, boolean) to authenticated;

create table public.telegram_allowed_senders (
  telegram_user_id bigint primary key,
  label text not null default '',
  added_by uuid references auth.users (id) on delete set null,
  created_at timestamptz not null default now()
);

create table public.telegram_event_drafts (
  id bigint generated by default as identity primary key,
  telegram_update_id bigint not null unique,
  telegram_sender_id bigint not null,
  sender_name text not null default '',
  source_chat_id text,
  source_message_id text,
  source_channel text,
  source_date timestamptz,
  message_text text not null,
  status text not null default 'pending'
    check (status in ('pending', 'published', 'rejected')),
  published_activity_id bigint references public.activities (id) on delete set null,
  created_at timestamptz not null default now()
);

grant select, insert, delete on public.telegram_allowed_senders to authenticated;
grant select, update on public.telegram_event_drafts to authenticated;
grant select on public.telegram_allowed_senders to service_role;
grant insert on public.telegram_event_drafts to service_role;
grant usage, select on sequence public.telegram_event_drafts_id_seq to service_role;

alter table public.telegram_allowed_senders enable row level security;
alter table public.telegram_event_drafts enable row level security;

